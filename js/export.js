// SpriteForge - exporters: pixdata.lua (runtime data), project JSON, PNG sheet.
import { encodeSprite } from "./mesh.js?v=1.0";
import { compileFrame, drawPrims } from "./vector.js?v=1.0";
import { rasterFrame, drawScaled } from "./raster.js?v=1.0";
import { composite, resolveColor, usedKeys } from "./model.js?v=1.0";
import { downscale } from "./quantize.js?v=1.0";

const luaStr = s => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
const luaNum = n => Number.isInteger(n) ? String(n) : String(Math.round(n * 1000) / 1000);
const luaVal = v => typeof v === "string" ? luaStr(v) : typeof v === "boolean" ? (v ? "true" : "false") : luaNum(v);
const ident = s => /^[A-Za-z_][A-Za-z0-9_]*$/.test(s) ? s : "[" + luaStr(s) + "]";

// Encode every frame (and every "separate" layer) of every sprite.
// Returns { entries: [{name, w, h, ax, ay, k, r, count}], total }
export function encodeProject(project) {
  const entries = [];
  const alphaOf = key => (project.palettes.base[key] || [0, 0, 0, 255])[3];
  for (const sp of Object.values(project.sprites)) {
    if (sp.kind === "vector") {
      const baseLayers = sp.layers.filter(L => !L.separate).map(L => L.name);
      sp.frames.forEach((f, i) => {
        const suffix = i === 0 ? "" : "#" + (i + 1);
        const pr = compileFrame(sp, i, baseLayers);
        entries.push(vecEntry(sp.name + suffix, sp, pr));
        for (const L of sp.layers.filter(L => L.separate)) entries.push(vecEntry(sp.name + "/" + L.name + suffix, sp, compileFrame(sp, i, [L.name])));
      });
      continue;
    }
    const baseLayers = sp.layers.filter(L => !L.separate).map(L => L.name);
    sp.frames.forEach((f, i) => {
      const suffix = i === 0 ? "" : "#" + (i + 1);
      const grid = composite(sp, i, baseLayers);
      const e = encodeSprite(grid, sp.w, sp.h, alphaOf);
      entries.push({ name: sp.name + suffix, w: sp.w, h: sp.h, ax: sp.ax, ay: sp.ay, ...e });
      for (const L of sp.layers.filter(L => L.separate)) {
        const g = composite(sp, i, [L.name]);
        const el = encodeSprite(g, sp.w, sp.h, alphaOf);
        entries.push({ name: sp.name + "/" + L.name + suffix, w: sp.w, h: sp.h, ax: sp.ax, ay: sp.ay, ...el });
      }
      if (sp.lod) {
        const g2 = downscale(grid, sp.w, sp.h);
        const W = Math.ceil(sp.w / 2), H = Math.ceil(sp.h / 2);
        const e2 = encodeSprite(g2, W, H, alphaOf);
        entries.push({ name: sp.name + "@2" + suffix, w: W, h: H, ax: sp.ax / 2, ay: (sp.ay + 1) / 2 - 1, lod: true, ...e2 });
      }
      if (sp.nine && i === 0) {
        const { l, t, r, b } = sp.nine;
        const xs = [[0, l], [l, sp.w - r], [sp.w - r, sp.w]], ys = [[0, t], [t, sp.h - b], [sp.h - b, sp.h]];
        const names = [["tl", "t", "tr"], ["l", "c", "r"], ["bl", "b", "br"]];
        for (let ry = 0; ry < 3; ry++) for (let rx = 0; rx < 3; rx++) {
          const [x0, x1] = xs[rx], [y0, y1] = ys[ry];
          const pw = x1 - x0, ph = y1 - y0;
          if (pw <= 0 || ph <= 0) continue;
          const pg = [];
          for (let y = y0; y < y1; y++) pg.push(grid[y].slice(x0, x1));
          const ep = encodeSprite(pg, pw, ph, alphaOf);
          entries.push({ name: sp.name + "~" + names[ry][rx], w: pw, h: ph, ax: 0, ay: ph - 1, piece: true, ...ep });
        }
      }
    });
  }
  return { entries, total: entries.reduce((a, e) => a + e.count, 0) };
}

function vecEntry(name, sp, prims) {
  const keys = [];
  for (const q of prims) if (!keys.includes(q.c)) keys.push(q.c);
  const p = [];
  for (const q of prims) p.push(q.a, q.x, q.y, q.w, q.h, q.r || 0, keys.indexOf(q.c) + 1);
  return { name, vector: true, w: sp.w, h: sp.h, ax: sp.ax, ay: sp.ay, k: keys, p, count: prims.length };
}

export function spriteCost(project, sp, lod = false) {
  if (sp.kind === "vector") return compileFrame(sp, 0).length;
  const alphaOf = key => (project.palettes.base[key] || [0, 0, 0, 255])[3];
  let grid = composite(sp, 0), w = sp.w, h = sp.h;
  if (lod) { grid = downscale(grid, w, h); w = Math.ceil(w / 2); h = Math.ceil(h / 2); }
  return encodeSprite(grid, w, h, alphaOf).count;
}

export function toLua(project) {
  const { entries } = encodeProject(project);
  const L = [];
  L.push("-- Generated by SpriteForge (Lua client scripts)");
  L.push("-- Project: " + project.name + "   Do not edit by hand: re-export from the .spriteforge.json file.");
  L.push("local D = {}");
  L.push("D.VERSION = " + (project.version || 1));
  L.push("D.PX = " + luaNum(project.px || 4));
  // palettes
  L.push("D.P = {}");
  for (const [pname, pal] of Object.entries(project.palettes)) {
    const parts = Object.entries(pal).map(([k, c]) => ident(k) + "={" + c.map(luaNum).join(",") + "}");
    L.push("D.P[" + luaStr(pname) + "] = {" + parts.join(", ") + "}");
  }
  // sprites
  L.push("D.S = {}");
  L.push("D.V = {}");
  for (const e of entries.filter(e => e.vector)) {
    L.push("D.V[" + luaStr(e.name) + "]={w=" + luaNum(e.w) + ",h=" + luaNum(e.h) + ",ax=" + luaNum(e.ax) + ",ay=" + luaNum(e.ay) +
      ",n=" + e.count + ",k={" + e.k.map(luaStr).join(",") + "},p={" + e.p.map(luaNum).join(",") + "}}");
  }
  for (const e of entries.filter(e => !e.vector)) {
    L.push("D.S[" + luaStr(e.name) + "]={w=" + e.w + ",h=" + e.h + ",ax=" + luaNum(e.ax) + ",ay=" + luaNum(e.ay) +
      ",n=" + e.count + ",k={" + e.k.map(luaStr).join(",") + "},r=" + luaStr(e.r) + (e.z === 2 ? ",z=2" : "") + "}");
  }
  // sprite meta
  L.push("D.A = {}");
  for (const sp of Object.values(project.sprites)) {
    const sep = sp.layers.filter(l => l.separate).map(l => luaStr(l.name));
    const nine = sp.nine ? ",nine={l=" + sp.nine.l + ",t=" + sp.nine.t + ",r=" + sp.nine.r + ",b=" + sp.nine.b + "}" : "";
    L.push("D.A[" + luaStr(sp.name) + "]={w=" + sp.w + ",h=" + sp.h + ",frames=" + sp.frames.length + ",fps=" + luaNum(sp.fps || 8) +
      ",layers={" + sp.layers.map(l => luaStr(l.name)).join(",") + "},separate={" + sep.join(",") + "}" +
      ",lod=" + (sp.lod ? "true" : "false") + ",tiles=" + (sp.tiles ? "true" : "false") + nine + (sp.kind === "vector" ? ",vector=true" : "") + "}");
  }
  // clips
  L.push("D.C = {}");
  for (const [cname, c] of Object.entries(project.clips)) {
    const tracks = (c.tracks || []).map(t => "{prop=" + luaStr(t.prop) + ",ease=" + luaStr(t.ease || "linear") +
      ",keys={" + (t.keys || []).map(k => "{" + luaNum(k.t) + "," + luaVal(k.v) + "}").join(",") + "}}");
    L.push("D.C[" + luaStr(cname) + "]={sprite=" + luaStr(c.sprite || "") + ",dur=" + luaNum(c.dur || 1) + ",loop=" + (c.loop ? "true" : "false") +
      ",tracks={" + tracks.join(",") + "}}");
  }
  // behaviors
  L.push("D.B = {}");
  for (const [bname, b] of Object.entries(project.behaviors)) {
    const params = Object.entries(b.params || {}).map(([k, v]) => ident(k) + "=" + luaNum(v));
    const states = Object.entries(b.states || {}).map(([sname, st]) => {
      const layers = Object.entries(st.layers || {}).map(([k, v]) => ident(k) + "=" + (v ? "true" : "false"));
      const on = (st.on || []).map(tr => {
        const f = [];
        if (tr.ev) f.push("ev=" + luaStr(tr.ev));
        if (tr.timer) f.push("timer={" + luaNum(tr.timer[0]) + "," + luaNum(tr.timer[1]) + "}");
        if (tr.param) { f.push("param=" + luaStr(tr.param)); if (tr.lt != null) f.push("lt=" + luaNum(tr.lt)); if (tr.gt != null) f.push("gt=" + luaNum(tr.gt)); }
        f.push("to=" + luaStr(tr.to));
        return "{" + f.join(",") + "}";
      });
      return ident(sname) + "={clip=" + (st.clip ? luaStr(st.clip) : "nil") + ",pal=" + (st.pal ? luaStr(st.pal) : "nil") +
        ",layers={" + layers.join(",") + "},on={" + on.join(",") + "}}";
    });
    L.push("D.B[" + luaStr(bname) + "]={sprite=" + luaStr(b.sprite || bname) + ",initial=" + luaStr(b.initial || "idle") +
      ",params={" + params.join(",") + "},states={" + states.join(",") + "}}");
  }
  L.push("return D");
  return L.join("\n") + "\n";
}

export function toJSON(project) { return JSON.stringify(project, null, 1); }

// One file for the game: data + runtime + a start script. Attach it to a Client Control Container.
const BUNDLE_MAIN = `
local shown = {}
local ready, tries = false, 0

local function start()
  Px.setup(script, TEMPLATE or "TPL_SPRITE", TAP_TEMPLATE or "TPL_HIT")
  local root = Px.root()
  if not root then return false end
  local before = Px.count
  for _, s in ipairs(SHOW) do
    if Px.has(s.sprite) then
      local a = Px.spawn(root, s.sprite, s.x or 0, s.y or 0, { px = s.size or Px.PX, pal = s.pal })
      if s.clip then a:play(s.clip) end
      if a.behavior then a:onTap(function(self) self:fire("tap") end) end
      shown[#shown + 1] = a
    end
  end
  if #shown > 0 and Px.count == before then
    for _, a in ipairs(shown) do a:destroy() end
    shown = {}
    return false
  end
  print("SpriteForge: " .. #shown .. " sprite(s) ready, rectangles: " .. Px.count)
  return true
end

function OnStart()
  script:EnableUpdate(true)
  ready = start()
end

function OnUpdate(dt)
  if not ready then
    tries = tries + 1
    if tries <= 120 then
      ready = start()
    elseif tries == 121 then
      print("SpriteForge: nothing was drawn. Check TEMPLATE at the top of this file (Image template Index) and that the file is attached to a Client Control Container")
    end
    return
  end
  Px.update(dt)
end

function OnDestroy()
  Px.clear()
end
`;

const stripComments = lua => lua.split("\n").filter(line => !/^\s*--/.test(line)).join("\n");

export function toBundle(project, setup, runtime) {
  const data = toLua(project).replace(/\s+$/, "");
  const rt = stripComments(runtime.replace(/^\uFEFF?local D = require\("pixdata"\)[^\n]*\n/, "")).replace(/\s+$/, "");
  const tpl = n => Number.isFinite(n) && n > 0 ? String(Math.round(n)) : "nil";
  const show = (setup.show || []).filter(s => project.sprites[s.sprite]).map(s =>
    "  { sprite = " + luaStr(s.sprite) + ", x = " + luaNum(+s.x || 0) + ", y = " + luaNum(+s.y || 0) + ", size = " + luaNum(+s.size || project.px || 4) + " },");
  const L = [];
  L.push("-- Generated by SpriteForge: sprites, runtime and start script in one file");
  L.push("local TEMPLATE = " + tpl(setup.template));
  L.push("local TAP_TEMPLATE = " + tpl(setup.tapTemplate));
  L.push("local SHOW = {");
  for (const line of show) L.push(line);
  L.push("}");
  L.push("");
  L.push("local D = (function()");
  L.push(data);
  L.push("end)()");
  L.push("");
  L.push("local Px = (function()");
  L.push(rt);
  L.push("end)()");
  L.push(BUNDLE_MAIN.replace(/\s+$/, ""));
  return L.join("\n") + "\n";
}

// PNG sheet of all frames of one sprite (for docs / reference)
export function spriteToCanvas(project, sp, frame = 0, scale = 8, palName = "base") {
  const cv = document.createElement("canvas");
  if (sp.kind === "vector") {
    const k = scale;
    cv.width = Math.max(1, Math.round(sp.w * k)); cv.height = Math.max(1, Math.round(sp.h * k));
    drawPrims(cv.getContext("2d"), compileFrame(sp, frame), key => resolveColor(project, key, palName), 0, 0, k);
    return cv;
  }
  const names = sp.layers.filter(L => L.visible).map(L => L.name);
  const src = rasterFrame(project, sp, frame, palName, names);
  if (scale === 1) return src;
  cv.width = Math.max(1, Math.round(sp.w * scale)); cv.height = Math.max(1, Math.round(sp.h * scale));
  drawScaled(cv.getContext("2d"), src, 0, 0, cv.width, cv.height);
  return cv;
}

export function download(name, text, type = "text/plain") {
  const blob = text instanceof Blob ? text : new Blob([text], { type });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob); a.download = name; a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}

// Import an existing pixdata.lua S-entry (or whole file) back into sprites.
export function fromLua(text) {
  const sprites = [];
  const re = /S\[\s*"([^"]+)"\s*\]\s*=\s*\{w=(\d+),h=(\d+),ax=(-?[\d.]+),ay=(-?[\d.]+)(?:,n=\d+)?,k=\{([^}]*)\},r="((?:[^"\\]|\\.)*)"(?:,z=(\d))?\}/g;
  let m;
  while ((m = re.exec(text))) {
    const keys = m[6].split(",").map(s => s.trim().replace(/^"|"$/g, "")).filter(Boolean);
    sprites.push({ name: m[1], w: +m[2], h: +m[3], ax: +m[4], ay: +m[5], k: keys, r: m[7].replace(/\\"/g, '"').replace(/\\\\/g, "\\"), z: m[8] ? +m[8] : 1 });
  }
  const pal = {};
  const pre = /P\[\s*"([^"]+)"\s*\]\s*=\s*\{([^\n]*)\}\s*$/gm;
  while ((m = pre.exec(text))) {
    const entries = {};
    const er = /(?:\["([^"]+)"\]|([A-Za-z_]\w*))=\{(\d+),(\d+),(\d+),(\d+)\}/g;
    let e;
    while ((e = er.exec(m[2]))) entries[e[1] || e[2]] = [+e[3], +e[4], +e[5], +e[6]];
    pal[m[1]] = entries;
  }
  const pal2 = /\["(\w+)"\]=\{(\d+),(\d+),(\d+),(\d+)\}/g; // legacy pixdata P table
  const legacy = {};
  while ((m = pal2.exec(text))) legacy[m[1]] = [+m[2], +m[3], +m[4], +m[5]];
  if (!pal.base && Object.keys(legacy).length) pal.base = legacy;
  return { sprites, palettes: pal, usedKeys };
}
