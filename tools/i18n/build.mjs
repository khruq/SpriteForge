import fs from "fs";
const dir = new URL(".", import.meta.url).pathname;
const keys = JSON.parse(fs.readFileSync(dir + "keys.json", "utf8"));
const langs = ["zh-CN","zh-TW","ja","ko","es","fr","ru","th","vi","de","id","pt","tr","it"];
const out = {};
const ph = s => (s.match(/\{[a-z]+\}/g) || []).sort().join(",");
let bad = 0;
for (const l of langs) {
  const arr = JSON.parse(fs.readFileSync(dir + l + ".json", "utf8"));
  if (arr.length !== keys.length) { console.error(l, "length", arr.length); process.exit(1); }
  out[l] = {};
  keys.forEach((k, i) => {
    if (ph(k) !== ph(arr[i])) { console.warn(l, i, "placeholders:", JSON.stringify(k), "->", JSON.stringify(arr[i])); bad++; }
    out[l][k] = arr[i];
  });
}
fs.writeFileSync(dir + "../../js/strings.js", "// Generated by tools/i18n/build.mjs - do not edit by hand.\nexport const STRINGS = " + JSON.stringify(out, null, 0) + ";\n");
console.log("strings.js written,", langs.length, "languages,", keys.length, "keys, placeholder mismatches:", bad);
